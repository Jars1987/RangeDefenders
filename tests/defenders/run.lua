-- Run from repository root: lua tests/defenders/run.lua all
local stub=dofile('tests/defenders/stub.lua')
local bot=dofile('tests/defenders/bot.lua')
local json=dofile('tests/defenders/json.lua')
local scenarios,order={},{}
local current={}
local function new(c) local h=stub.new(c); current[#current+1]=h; return h end
local function scenario(name,fn) scenarios[name]=fn; order[#order+1]=name end
local function ready(c)
  local h=new(c); h:tick(90); return h
end
local function play(h) h:key('select'); assert(h:find('/^\\'),'player missing') end
local function clear(h)
  bot.until_true(h,function(b) return b:has('WAVE 2') end,4000)
end
scenario('defenders_title',function()
  local h=ready({welcome=0})
  assert(h:has('Top score each day wins !LAMPs.'))
  assert(h:has('Finals at the Range booth.'))
  assert(h:has('Link X to earn !LAMPs'))
  assert(not h:has('Welcome bonus:'))
  assert(#h.awards==0 and #h:requests('/v1/welcome/claim')==0)
  local w=ready({welcome=25})
  assert(w:has('Welcome bonus: 25 !LAMPs'))
  assert(w:has('+25 !LAMPs welcome bonus'))
  assert(#w.awards==1)
  assert(#w:requests('/v1/hello')==1)
  local again=ready({welcome=25,store=w.store,eligible=false})
  assert(#again.awards==0,'welcome awarded twice')
end)
scenario('defenders_play',function()
  local h=ready(); play(h); clear(h)
  assert(h:has('WAVE CLEARED +1 LIFE'))
  assert(not h:has('RANGE ALERT'))
end)
scenario('defenders_boss',function()
  local h=ready(); play(h)
  bot.until_true(h,function(b) return b:find('<LAZARUS>') end,800,'boss')
  bot.until_true(h,function(b) return b:has('LAZARUS +300') end,1200,'boss')
  bot.breach(h); h:tick(80)
  local calls=h:requests('/v1/defenders/score')
  assert(#calls>=1 and calls[1].body.boss==true,'boss kill not submitted')
end)
scenario('defenders_breach',function()
  local h=ready(); play(h); bot.breach(h)
  assert(h:has('RANGE ALERT'))
  assert(h:has('FAKE MINT SITE') or h:has('RAINBOW DRAINER') or h:has('WALLET DRAINER'),'threat name missing')
  h:key('right'); assert(h:has('Jose Santos and Range'))
  h:key('back'); assert(h:has('RANGE ALERT'))
  h:key('select'); assert(h:has('WAVE 1'))
end)
scenario('defenders_qr',function()
  local h=ready({server='https://r.test'})
  h:key('down')
  local q=h:find('https://r.test/go/screening?a=defenders')
  assert(q and q.kind=='qr' and #q.text_value<=40)
  h:key('back'); assert(h:has('Solana Defenders'))
  local default=ready(); default:key('down')
  assert(default:find('https://rng.example/go/screening?a=defenders'))
  local old=ready({noqr=true}); old:key('down')
  assert(old:has('QR unavailable')); old:key('back'); play(old)
end)
scenario('defenders_offline',function()
  local h=ready({offline=true}); assert(h:has('offline')); play(h); clear(h)
  bot.breach(h); h:tick(200)
  assert(h:has('offline - score saved for retry'))
  assert(h.store.score_pending and h.store.best>0)
  h:key('down'); assert(h:find('https://rng.example/go/screening?a=defenders'))
  h:key('back'); h:key('select'); assert(h:has('WAVE 1'))
end)
scenario('defenders_score_submit',function()
  local h=ready({responses={['/v1/defenders/score']={'timeout'}}})
  play(h); clear(h); bot.breach(h); h:tick(400)
  local calls=h:requests('/v1/defenders/score')
  assert(#calls==2,'score retry missing')
  assert(calls[1].body.op==calls[2].body.op,'operation changed on retry')
  assert(#h.scores==1,'server duplicated score')
  assert(h:has('RANK 2'))
  for _,n in ipairs({'ALICE','BOB','CAROL','DAVE','ERIN'}) do assert(h:has(n),'top five missing '..n) end
  assert(h:has('UP share your best'))
  h:key('up'); assert(h:find('https://rng.example/r/a'),'share QR missing')
  local call=h:requests('/v1/share')[1]
  assert(call and call.body.kind=='score')
  assert(h.store.best>0 and not h.store.score_pending)
end)
scenario('defenders_welcome_needsx',function()
  local h=ready({welcome=25,needsx=true})
  assert(h:has('Link X to earn !LAMPs') and #h.awards==1)
  assert(not h:has('+25 !LAMPs welcome bonus'))
  h:tick(1000); assert(#h.awards==1,'award repeated this launch')
  local linked=ready({welcome=25,store=h.store,eligible=false})
  assert(#linked.awards==1 and linked.store.welcome.done,'claimed entitlement not retried after linking X')
end)
scenario('defenders_budget',function()
  local h=ready({welcome=25}); play(h)
  local allocated=#h.objects
  bot.until_true(h,function(b) return b:find('<LAZARUS>') end,800,'boss')
  for _=1,60 do bot.step(h,'boss') end
  assert(#h.objects==allocated,'widgets allocated during play')
  h:key('back'); assert(h:has('Paused'))
  local p=h:find('Paused'); h:tick(100); assert(p.visible)
  h:key('select'); clear(h)
  assert(h.max_live<=64 and h.max_instructions<200000)
  assert(h.peak_heap<=32768,'heap exceeds 32 KB target: '..h.peak_heap)
  local f=assert(io.open('apps/defenders/app.json')); local manifest=json.decode(f:read('*a')); f:close()
  assert(manifest.id=='range-defenders' and manifest.name=='Solana Defenders' and #manifest.name<=20)
  assert(manifest.category=='games' and manifest.icon=='play' and manifest.accent=='14F195')
  assert(table.concat(manifest.permissions,',')=='led,lamps,profile,http')
  assert(#manifest.hosts==1 and manifest.hosts[1]=='rng.example')
end)
scenario('defenders_welcome_denied',function()
  local h=ready({welcome=25,award_denied=true})
  assert(h:has('Welcome award denied') and not h.store.welcome.done)
  assert(#h.awards==1); play(h); clear(h)
  local zero=ready({welcome=25,capzero=true})
  assert(zero:has('Welcome award unavailable') and #zero.awards==1)
end)
scenario('defenders_response_failures',function()
  for _,mode in ipairs({'status','truncated','badjson','badshape','notok'}) do
    local h=ready({responses={['/v1/hello']={mode}}})
    assert(h:has('offline'),mode..' not treated as offline')
    play(h); h:tick(200)
    assert(#h:requests('/v1/hello')==2,mode..' did not recover')
    assert(not h:has('offline'),mode..' did not clear offline')
  end
end)
scenario('defenders_late_callback',function()
  local h=ready({late=true}); play(h); clear(h); bot.breach(h)
  h:tick(650)
  assert(#h.scores==1)
  local calls=h:requests('/v1/defenders/score')
  assert(#calls==2 and calls[1].body.op==calls[2].body.op)
  assert(h:has('RANK 2') and not h.store.score_pending)
end)
scenario('defenders_restart',function()
  local h=ready({offline=true}); play(h); clear(h); bot.breach(h)
  local op=h.store.score_pending.op
  h:invoke(h.env.on_exit)
  local online=ready({store=h.store})
  local calls=online:requests('/v1/defenders/score')
  assert(#calls==1 and calls[1].body.op==op,'restart replaced pending operation')
  assert(online:has('BEST '..h.store.best))
  assert(not online.store.score_pending)
  local w=ready({welcome=25,award_timeout=true})
  local ambiguous=ready({welcome=25,store=w.store,eligible=false})
  assert(#ambiguous.awards==0,'ambiguous award replayed')
end)
scenario('defenders_welcome_retry',function()
  local h=ready({welcome=25,responses={['/v1/welcome/claim']={'timeout'}}})
  assert(#h.awards==0)
  h:tick(250)
  local calls=h:requests('/v1/welcome/claim')
  assert(#calls==2 and calls[1].body.op==calls[2].body.op)
  assert(#h.awards==1 and h.store.welcome.done)
end)
scenario('defenders_pending_runs',function()
  local h=ready({offline=true}); play(h); bot.breach(h)
  local first=h.store.score_pending.op
  h:key('select'); clear(h); bot.breach(h)
  assert(h.store.score_next and h.store.score_next.score>0)
  local second=h.store.score_next.op
  assert(first~=second)
  h:invoke(h.env.on_exit)
  local online=ready({store=h.store}); online:tick(150)
  local calls=online:requests('/v1/defenders/score')
  assert(#calls==2 and calls[1].body.op==first and calls[2].body.op==second)
  assert(not online.store.score_pending and not online.store.score_next)
end)
scenario('defenders_board_validation',function()
  local h=ready({mutate=function(path,r,n)
    if path=='/v1/defenders/score' and n==1 then r.top[1].s='invalid' end
    return r
  end})
  play(h); bot.breach(h); h:tick(40)
  assert(h:has('offline'),'invalid leaderboard accepted')
  assert(h.store.score_pending,'invalid leaderboard discarded operation')
  h:tick(200)
  assert(h:has('RANK 2'))
end)
scenario('defenders_exit',function()
  local h=new(); h:invoke(h.env.on_exit); h:tick(300)
  assert(#h.calls==0,'callback ran after exit')
  assert(h.led[1]==0 and h.led[2]==0 and h.led[3]==0)
  local menu=ready(); assert(menu:key('back')==false)
end)
scenario('defenders_module_lifecycle',function()
  local h=ready({welcome=25,http_delay=2000})
  assert(h.env.package==nil,'stub exposed an unavailable OS API')
  assert(not pcall(h.env.collectgarbage,'collect'),'stub allowed unavailable manual GC')
  play(h); h:tick(400)
  assert(h:has('WAVE 1') and #h.awards==1,'20-second play lost delayed welcome reward')
  assert(h.resident['@apps/defenders/lib/play.lua'])
  assert(not h.resident['@apps/defenders/lib/menu.lua'] and not h.resident['@apps/defenders/lib/net.lua'],'phase code leaked into play')
  for _=1,12 do
    h:key('back'); assert(h:has('Paused'))
    assert(not h.resident['@apps/defenders/lib/play.lua'],'play code retained by paused screen')
    h:key('back'); h:key('right'); assert(h:has('Jose Santos and Range'))
    h:key('down'); h:key('back'); play(h)
  end
  assert(h.peak_total<=34*1024 and h.max_live==60)
end)
local target=arg[1] or 'all'
if target~='all' then assert(scenarios[target],'unknown scenario: '..target); order={target} end
local passed,worst=0,0
local proxies={}
for _,name in ipairs(order) do
  current={}
  local ok,err=pcall(scenarios[name])
  local instructions,live,heap,total=0,0,0,0
  for _,h in ipairs(current) do
    instructions=math.max(instructions,h.max_instructions); live=math.max(live,h.max_live); heap=math.max(heap,h.peak_heap); total=math.max(total,h.peak_total)
    for path,bytes in pairs(h.proxies) do proxies[path]=math.max(proxies[path] or 0,bytes) end
  end
  worst=math.max(worst,total)
  print(string.format('%s %s | max instructions/callback=%d | max live UI=%d | peak heap estimate=%d bytes | peak code+heap=%d bytes',
    ok and 'PASS' or 'FAIL',name,instructions,live,heap,total))
  if ok then passed=passed+1 else print(tostring(err)) end
end
local paths={}; for path in pairs(proxies) do paths[#paths+1]=path end; table.sort(paths)
for _,path in ipairs(paths) do print(string.format('CODE %s proxy=%d bytes',path:sub(2),proxies[path])) end
print(string.format('worst peak code+heap=%d bytes (limit 34816)',worst))
print(string.format('%d/%d PASS',passed,#order))
if passed~=#order then os.exit(1) end
